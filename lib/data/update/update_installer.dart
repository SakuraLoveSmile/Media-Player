import 'dart:io';

import 'package:archive/archive_io.dart';
import 'package:flutter/foundation.dart' show visibleForTesting;
import 'package:open_filex/open_filex.dart';
import 'package:url_launcher/url_launcher.dart';

import 'update_models.dart';
import 'update_service.dart';

/// open_filex 5 renamed its result type to `OpenResult`; keep the
/// updater-facing name so the frozen installer API stays stable.
typedef OpenFileResult = OpenResult;

/// Starts a process; injectable so no test ever launches a real updater.
typedef ProcessStarter = Future<Process> Function(
  String executable,
  List<String> arguments, {
  ProcessStartMode mode,
});

/// Installs a downloaded package on Android, Windows and macOS.
///
/// The install itself must outlive this process, so the desktop platforms
/// generate a small helper script, launch it detached and terminate the app.
/// Every process/URL entry point is injectable for unit tests.
class UpdateInstaller {
  UpdateInstaller({
    ProcessStarter? processStarter,
    Never Function(int exitCode)? exitProcess,
    Future<bool> Function(Uri url)? urlOpener,
    @visibleForTesting this.targetOverride,
    @visibleForTesting this.executablePathOverride,
    @visibleForTesting
    Future<OpenFileResult> Function(File package)? androidOpener,
  }) : _processStarter = processStarter ?? _startProcess,
       _exitProcess = exitProcess ?? exit,
       _urlOpener = urlOpener ?? _launchUrl,
       _androidOpener = androidOpener ?? _openApk;

  /// Test-only override of the platform detection.
  @visibleForTesting
  final UpdateTarget? targetOverride;

  /// Test-only override of the running executable path.
  @visibleForTesting
  final String? executablePathOverride;

  final ProcessStarter _processStarter;
  final Never Function(int exitCode) _exitProcess;
  final Future<bool> Function(Uri url) _urlOpener;
  final Future<OpenFileResult> Function(File package) _androidOpener;

  static const String _apkMimeType = 'application/vnd.android.package-archive';

  /// Installs [package] for the current platform.
  ///
  /// Android shows the system installer and returns; macOS/Windows launch a
  /// detached helper and never return because the app has to exit first.
  /// Unsupported platforms fall back to opening the release page.
  Future<void> installUpdate(File package, AppRelease release) async {
    final UpdateTarget target = _target;
    if (target == UpdateTarget.unsupported) {
      await openReleasePage(release);
      return;
    }
    if (!await package.exists()) {
      throw const UpdateException('安装包不存在或已被清理，请重新下载。');
    }
    switch (target) {
      case UpdateTarget.android:
        await _installAndroid(package);
        return;
      case UpdateTarget.macos:
        await _installMacos(package);
        return;
      case UpdateTarget.windows:
        await _installWindows(package);
        return;
      case UpdateTarget.unsupported:
        return;
    }
  }

  /// Opens the release page in the system browser.
  Future<void> openReleasePage(AppRelease release) async {
    final bool opened;
    try {
      opened = await _urlOpener(release.pageUrl);
    } catch (_) {
      throw const UpdateException('无法打开浏览器，请手动访问发布页。');
    }
    if (!opened) {
      throw const UpdateException('无法打开浏览器，请手动访问发布页。');
    }
  }

  /// Windows updater command line; exposed so the argument contract can be
  /// asserted without running PowerShell.
  @visibleForTesting
  static List<String> buildWindowsUpdaterArguments({
    required String scriptPath,
    required int processId,
    required String sourcePath,
    required String targetPath,
    required String executableName,
    required String logPath,
  }) {
    return <String>[
      '-NoProfile',
      '-ExecutionPolicy',
      'Bypass',
      '-WindowStyle',
      'Hidden',
      '-File',
      scriptPath,
      '-ProcessId',
      '$processId',
      '-SourcePath',
      sourcePath,
      '-TargetPath',
      targetPath,
      '-ExecutableName',
      executableName,
      '-LogPath',
      logPath,
    ];
  }

  /// macOS helper script: wait for the app to exit, replace the bundle, clear
  /// the quarantine flag, relaunch and remove the extraction directory.
  @visibleForTesting
  static String buildMacUpdaterScript({
    required String sourceAppPath,
    required String targetAppPath,
    required int processId,
    required String extractedRootPath,
  }) {
    final String source = _shellQuote(sourceAppPath);
    final String target = _shellQuote(targetAppPath);
    final String extractRoot = _shellQuote(extractedRootPath);
    return <String>[
      '#!/bin/bash',
      '# Generated by the MediaPlayer updater.',
      '# Wait for the running app to quit, then swap the app bundle.',
      'set -u',
      '',
      'APP_PID=$processId',
      'SOURCE_APP=$source',
      'TARGET_APP=$target',
      'EXTRACT_ROOT=$extractRoot',
      '',
      '# Give the old process up to 60 seconds to exit.',
      'attempt=0',
      'while kill -0 "\$APP_PID" 2>/dev/null && [ "\$attempt" -lt 300 ]; do',
      '  sleep 0.2',
      '  attempt=\$((attempt + 1))',
      'done',
      '',
      'rm -rf "\$TARGET_APP"',
      '/usr/bin/ditto "\$SOURCE_APP" "\$TARGET_APP"',
      '/usr/bin/xattr -dr com.apple.quarantine "\$TARGET_APP" 2>/dev/null || true',
      'open "\$TARGET_APP"',
      'rm -rf "\$EXTRACT_ROOT"',
      '',
    ].join('\n');
  }

  UpdateTarget get _target {
    final UpdateTarget? override = targetOverride;
    if (override != null) return override;
    if (Platform.isAndroid) return UpdateTarget.android;
    if (Platform.isWindows) return UpdateTarget.windows;
    if (Platform.isMacOS) return UpdateTarget.macos;
    return UpdateTarget.unsupported;
  }

  Future<void> _installAndroid(File package) async {
    final OpenResult result;
    try {
      result = await _androidOpener(package);
    } catch (_) {
      throw const UpdateException('无法调起系统安装器，请手动打开下载目录安装。');
    }
    if (result.type != ResultType.done) {
      throw const UpdateException('无法调起系统安装器，请手动打开下载目录安装。');
    }
  }

  Future<void> _installMacos(File package) async {
    final String executablePath =
        executablePathOverride ?? Platform.resolvedExecutable;
    final Directory targetApp = _macAppBundleOf(executablePath);
    if (!await _isWritableDirectory(targetApp.parent)) {
      throw const UpdateException('没有写入权限，无法自动更新，请打开下载页手动安装。');
    }

    final Directory extractRoot = await _createTempDirectory();
    final Directory sourceApp;
    try {
      sourceApp = await _extractMacApp(package, extractRoot);
    } catch (_) {
      await _deleteQuietly(extractRoot);
      rethrow;
    }

    final File script;
    try {
      script = await _writeMacUpdaterScript(
        sourceApp: sourceApp,
        targetApp: targetApp,
        extractRoot: extractRoot,
      );
    } catch (_) {
      await _deleteQuietly(extractRoot);
      throw const UpdateException('无法准备更新脚本，请打开下载页手动安装。');
    }

    try {
      await _processStarter(
        script.path,
        const <String>[],
        mode: ProcessStartMode.detached,
      );
    } catch (_) {
      await _deleteQuietly(extractRoot);
      await _deleteQuietly(script);
      throw const UpdateException('无法启动安装程序，请打开下载页手动安装。');
    }
    _exitProcess(0);
  }

  Future<void> _installWindows(File package) async {
    final String executablePath =
        executablePathOverride ?? Platform.resolvedExecutable;
    final File executable = File(executablePath);
    final Directory targetDir = executable.parent;
    final Directory extractRoot = await _createTempDirectory();
    try {
      final List<int> bytes = await package.readAsBytes();
      final Archive archive = ZipDecoder().decodeBytes(bytes);
      await extractArchiveToDisk(archive, extractRoot.path, throwOnError: true);
    } catch (_) {
      await _deleteQuietly(extractRoot);
      throw const UpdateException('解压安装包失败，请打开下载页手动安装。');
    }

    final String logPath =
        '${Directory.systemTemp.path}${Platform.pathSeparator}'
        'mediaplayer-update-$pid.log';
    final File script;
    try {
      script = await _writeWindowsUpdaterScript();
    } catch (_) {
      await _deleteQuietly(extractRoot);
      throw const UpdateException('无法准备更新脚本，请打开下载页手动安装。');
    }

    final List<String> arguments = buildWindowsUpdaterArguments(
      scriptPath: script.path,
      processId: pid,
      sourcePath: extractRoot.path,
      targetPath: targetDir.path,
      executableName: _basename(executablePath),
      logPath: logPath,
    );
    try {
      await _processStarter(
        'powershell.exe',
        arguments,
        mode: ProcessStartMode.detached,
      );
    } catch (_) {
      await _deleteQuietly(extractRoot);
      await _deleteQuietly(script);
      throw const UpdateException('无法启动安装程序，请打开下载页手动安装。');
    }
    _exitProcess(0);
  }

  /// `.../Media Player.app/Contents/MacOS/Media Player` -> `.../Media Player.app`.
  static Directory _macAppBundleOf(String executablePath) {
    // Three parents up from the executable file: MacOS -> Contents -> .app.
    return File(executablePath).parent.parent.parent;
  }

  Future<Directory> _extractMacApp(File package, Directory extractRoot) async {
    final ProcessResult result;
    try {
      result = await Process.run('ditto', <String>[
        '-x',
        '-k',
        package.path,
        extractRoot.path,
      ]);
    } on ProcessException {
      throw const UpdateException('当前系统缺少解压工具，请打开下载页手动安装。');
    }
    if (result.exitCode != 0) {
      throw UpdateException(
        '解压安装包失败（ditto 退出码 ${result.exitCode}），请打开下载页手动安装。',
      );
    }
    final Directory? app = await _findAppBundle(extractRoot);
    if (app == null) {
      throw const UpdateException('安装包中未找到应用程序，请打开下载页手动安装。');
    }
    return app;
  }

  Future<Directory?> _findAppBundle(Directory root, [int depth = 0]) async {
    if (depth > 2) return null;
    await for (final FileSystemEntity entity in root.list(followLinks: false)) {
      if (entity is! Directory) continue;
      if (entity.path.toLowerCase().endsWith('.app')) return entity;
      final Directory? nested = await _findAppBundle(entity, depth + 1);
      if (nested != null) return nested;
    }
    return null;
  }

  Future<File> _writeMacUpdaterScript({
    required Directory sourceApp,
    required Directory targetApp,
    required Directory extractRoot,
  }) async {
    final File script = File(
      '${Directory.systemTemp.path}${Platform.pathSeparator}'
      'mediaplayer-update-$pid-${DateTime.now().microsecondsSinceEpoch}.sh',
    );
    final String content = buildMacUpdaterScript(
      sourceAppPath: sourceApp.path,
      targetAppPath: targetApp.path,
      processId: pid,
      extractedRootPath: extractRoot.path,
    );
    await script.writeAsString(content, flush: true);
    final ProcessResult chmod = await Process.run('chmod', <String>[
      'u+x',
      script.path,
    ]);
    if (chmod.exitCode != 0) {
      await _deleteQuietly(script);
      throw UpdateException('无法准备更新脚本（chmod 退出码 ${chmod.exitCode}）');
    }
    return script;
  }

  Future<File> _writeWindowsUpdaterScript() async {
    final File script = File(
      '${Directory.systemTemp.path}${Platform.pathSeparator}'
      'mediaplayer-update-$pid-${DateTime.now().microsecondsSinceEpoch}.ps1',
    );
    await script.writeAsString(_windowsUpdaterScript, flush: true);
    return script;
  }

  Future<bool> _isWritableDirectory(Directory directory) async {
    if (!await directory.exists()) return false;
    final File probe = File(
      '${directory.path}${Platform.pathSeparator}'
      '.mediaplayer-update-probe-$pid-${DateTime.now().microsecondsSinceEpoch}',
    );
    var writable = false;
    try {
      await probe.writeAsString('probe', flush: true);
      writable = true;
    } on FileSystemException {
      writable = false;
    }
    await _deleteQuietly(probe);
    return writable;
  }

  Future<Directory> _createTempDirectory() async {
    try {
      return await Directory.systemTemp.createTemp('mediaplayer-update-');
    } on FileSystemException {
      throw const UpdateException('无法创建临时目录，请检查存储空间后重试。');
    }
  }

  static String _shellQuote(String value) =>
      "'${value.replaceAll("'", r"'\''")}'";

  static String _basename(String path) {
    final int slash = path.lastIndexOf('/');
    final int backslash = path.lastIndexOf(r'\');
    final int index = slash > backslash ? slash : backslash;
    return index >= 0 ? path.substring(index + 1) : path;
  }

  static Future<void> _deleteQuietly(FileSystemEntity entity) async {
    try {
      if (await entity.exists()) {
        await entity.delete(recursive: true);
      }
    } catch (_) {
      return;
    }
  }

  static Future<Process> _startProcess(
    String executable,
    List<String> arguments, {
    ProcessStartMode mode = ProcessStartMode.normal,
  }) {
    return Process.start(executable, arguments, mode: mode);
  }

  static Future<bool> _launchUrl(Uri url) => launchUrl(url);

  static Future<OpenResult> _openApk(File package) =>
      OpenFilex.open(package.path, type: _apkMimeType);

  static final String _windowsUpdaterScript =
      r'''
param(
  [Parameter(Mandatory = $true)][int]$ProcessId,
  [Parameter(Mandatory = $true)][string]$SourcePath,
  [Parameter(Mandatory = $true)][string]$TargetPath,
  [Parameter(Mandatory = $true)][string]$ExecutableName,
  [Parameter(Mandatory = $true)][string]$LogPath
)

$ErrorActionPreference = 'Stop'

function Write-UpdateLog([string]$Message) {
  Add-Content -LiteralPath $LogPath -Value (
    "[{0}] {1}" -f (Get-Date -Format o), $Message
  ) -ErrorAction SilentlyContinue
}

try {
  Write-UpdateLog "waiting for process $ProcessId to exit"
  $deadline = (Get-Date).AddSeconds(60)
  while ((Get-Process -Id $ProcessId -ErrorAction SilentlyContinue) -and
    ((Get-Date) -lt $deadline)) {
    Start-Sleep -Milliseconds 200
  }
  Write-UpdateLog "copying $SourcePath to $TargetPath"
  Copy-Item -Path (Join-Path $SourcePath '*') -Destination $TargetPath -Recurse -Force
  Write-UpdateLog "restarting $ExecutableName"
  Start-Process -FilePath (Join-Path $TargetPath $ExecutableName) -WorkingDirectory $TargetPath
  Write-UpdateLog "update complete"
} catch {
  Write-UpdateLog ("update failed: " + $_)
} finally {
  if (Test-Path -LiteralPath $SourcePath) {
    Remove-Item -LiteralPath $SourcePath -Recurse -Force -ErrorAction SilentlyContinue
  }
}
'''
          .trimLeft()
          .replaceAll('\n', '\r\n');
}

/// Platform the updater installs for; [UpdateTarget.unsupported] falls back to
/// opening the release page.
enum UpdateTarget { android, windows, macos, unsupported }
